import * as fs from 'fs';
import * as path from 'path';

interface ColorValue {
  light: string;
  dark: string;
}

interface TokenItem {
  type: string;
  value: ColorValue | string;
  description?: string;
}

interface TokensData {
  name?: string;
  modes?: Record<string, string>;
  tokens?: Record<string, any>;
  [key: string]: any;
}

interface ParsedColor {
  name: string;
  light: string;
  dark: string;
  lightHsl: string;
  darkHsl: string;
}

const TOKENS_FILE = path.resolve(process.cwd(), 'tokens.json');
const GLOBALS_CSS_FILE = path.resolve(process.cwd(), 'src/app/globals.css');

const MARKER_START = '  /* ==========================================================================\n     FIGMA DESIGN TOKENS (GENERATED BY scripts/parse-tokens.ts - DO NOT EDIT)\n     Source: tokens.json\n     ========================================================================== */';
const MARKER_END = '  /* ==========================================================================\n     END FIGMA DESIGN TOKENS\n     ========================================================================== */';

function hexToHsl(hex: string): string {
  hex = hex.replace('#', '');
  if (hex.length === 3) hex = hex.split('').map(c => c + c).join('');
  const num = parseInt(hex, 16);
  const r = ((num >> 16) & 255) / 255;
  const g = ((num >> 8) & 255) / 255;
  const b = (num & 255) / 255;

  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  let h = 0, s = 0, l = (max + min) / 2;

  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = (g - b) / d + (g < b ? 6 : 0); break;
      case g: h = (b - r) / d + 2; break;
      case b: h = (r - g) / d + 4; break;
    }
    h = Math.round(h * 60);
  }
  s = Math.round(s * 100);
  l = Math.round(l * 100);
  return `${h} ${s}% ${l}%`;
}

function normalizeTokenName(pathParts: string[]): string {
  return pathParts
    .join('-')
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '-');
}

function parseTokensJson(data: TokensData): ParsedColor[] {
  const colors: ParsedColor[] = [];
  const rootTokens = data.tokens || data;

  function traverse(node: any, currentPath: string[] = []): void {
    if (!node || typeof node !== 'object') return;

    if ('type' in node && 'value' in node) {
      const token = node as TokenItem;
      const tokenType = String(token.type).toLowerCase();

      if (tokenType === 'color') {
        const name = normalizeTokenName(currentPath);
        let light = '#000000';
        let dark = '#000000';

        if (typeof token.value === 'object' && token.value !== null) {
          const valObj = token.value as any;
          light = valObj.light || valObj['Light'] || valObj.default || '#000000';
          dark = valObj.dark || valObj['Dark'] || valObj['Dark (Default)'] || valObj.default || '#000000';
        } else if (typeof token.value === 'string') {
          light = token.value;
          dark = token.value;
        }

        colors.push({
          name,
          light,
          dark,
          lightHsl: hexToHsl(light),
          darkHsl: hexToHsl(dark)
        });
      }
      return;
    }

    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith('$')) continue;
      traverse(child, [...currentPath, key]);
    }
  }

  traverse(rootTokens);
  return colors;
}

export function syncTokens(): void {
  console.log(`[sync:tokens] Membaca tokens dari: ${TOKENS_FILE}`);

  if (!fs.existsSync(TOKENS_FILE)) {
    throw new Error(`File tokens.json tidak ditemukan di: ${TOKENS_FILE}`);
  }

  const rawContent = fs.readFileSync(TOKENS_FILE, 'utf8');
  const data = JSON.parse(rawContent);
  const colors = parseTokensJson(data);

  if (colors.length === 0) {
    throw new Error('Tidak ditemukan token warna di tokens.json!');
  }

  console.log(`[sync:tokens] Ditemukan ${colors.length} token warna untuk disinkronkan.`);

  if (!fs.existsSync(GLOBALS_CSS_FILE)) {
    throw new Error(`File globals.css tidak ditemukan di: ${GLOBALS_CSS_FILE}`);
  }

  let css = fs.readFileSync(GLOBALS_CSS_FILE, 'utf8');

  // Cari accent.primary untuk sync ke --primary dan --ring HSL
  const accentToken = colors.find(c => c.name === 'accent-primary');

  // Buat baris variabel untuk :root
  const rootVarLines = colors.map(c => `    --color-${c.name}: ${c.light};`);
  if (accentToken) {
    rootVarLines.push(`    --primary: ${accentToken.lightHsl};`);
    rootVarLines.push(`    --ring: ${accentToken.lightHsl};`);
  }

  // Buat baris variabel untuk .dark
  const darkVarLines = colors.map(c => `    --color-${c.name}: ${c.dark};`);
  if (accentToken) {
    darkVarLines.push(`    --primary: ${accentToken.darkHsl};`);
    darkVarLines.push(`    --ring: ${accentToken.darkHsl};`);
  }

  const tokenBlock = `${MARKER_START}
    /* Token Colors (Auto-Synced from Figma) */
${rootVarLines.join('\n')}
${MARKER_END}`;

  const darkTokenBlock = `${MARKER_START}
    /* Token Colors (Auto-Synced from Figma) */
${darkVarLines.join('\n')}
${MARKER_END}`;

  // Sisipkan ke :root
  if (css.includes(MARKER_START)) {
    // Replace existing block
    const parts = css.split(MARKER_START);
    // There are two blocks: one in :root and one in .dark
    if (parts.length >= 3) {
      const beforeRoot = parts[0];
      const afterRoot = parts[1].substring(parts[1].indexOf(MARKER_END) + MARKER_END.length);
      const afterDark = parts[2].substring(parts[2].indexOf(MARKER_END) + MARKER_END.length);

      css = beforeRoot + tokenBlock + afterRoot.substring(0, afterRoot.indexOf('.dark {')) + '.dark {\n' + darkTokenBlock + afterDark;
    }
  } else {
    // Sisipkan pertama kali ke dalam :root { ... } dan .dark { ... }
    css = css.replace(':root {', `:root {\n${tokenBlock}`);
    css = css.replace('.dark {', `.dark {\n${darkTokenBlock}`);
  }

  fs.writeFileSync(GLOBALS_CSS_FILE, css, 'utf8');
  console.log(`[sync:tokens] BERHASIL! File ${GLOBALS_CSS_FILE} telah disinkronkan dengan tema Figma.`);
}

if (require.main === module || process.argv[1]?.endsWith('parse-tokens.ts')) {
  try {
    syncTokens();
  } catch (err: any) {
    console.error(`[sync:tokens] ERROR: ${err.message}`);
    process.exit(1);
  }
}
